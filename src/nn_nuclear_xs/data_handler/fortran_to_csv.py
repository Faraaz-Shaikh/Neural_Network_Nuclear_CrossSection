"""Convert a fixed-width GDR ``.dat`` table into a clean CSV file.

The input file consists of
  * full-line comments beginning with ``#`` (anywhere in the file),
  * a comment line declaring the Fortran record format, e.g.
    ``# Format: 2I4, 9f9.3, I5``,
  * the column names on line 4 (also a comment line),
  * fixed-width data records in which missing values are blank fields.

Because missing values are represented by blanks, whitespace tokenisation is
unsound (it silently shifts values into the wrong columns). Records are
therefore sliced by the field widths declared in the format line.

Note: This file was generated by Claude Opus 5.5 Medium on 21 Oct 2026.
"""

import csv
import re
from collections.abc import Callable, Iterator, Sequence
from pathlib import Path
from typing import NamedTuple

from nn_nuclear_xs.config.app_config import cfg


class Field(NamedTuple):
    """A single fixed-width field: half-open slice [start, stop) and a validator."""

    start: int
    stop: int
    parser: Callable[[str], object]


def _parse_fortran_format(spec: str) -> list[tuple[int, Callable[[str], object]]]:
    """Expand a simple Fortran edit-descriptor list into (width, parser) pairs.

    Supports ``rIw`` and ``rFw.d`` / ``rEw.d`` / ``rDw.d`` / ``rGw.d``.
    """
    fields: list[tuple[int, Callable[[str], object]]] = []
    for raw in spec.split(","):
        token = raw.strip()
        descriptor_re = cfg.data_config.gdr_format.format_descriptor_regex
        match = re.compile(descriptor_re, re.IGNORECASE).match(token)
        if match is None:
            msg = f"Unsupported Fortran edit descriptor: {token!r}"
            raise ValueError(msg)
        repeat = int(match["repeat"] or 1)
        width = int(match["width"])
        parser: Callable[[str], object] = int if match["kind"].upper() == "I" else float
        fields.extend((width, parser) for _ in range(repeat))
    return fields


def _build_layout(spec: str) -> list[Field]:
    """Convert widths into cumulative column offsets."""
    layout: list[Field] = []
    offset = 0
    for width, parser in _parse_fortran_format(spec):
        layout.append(Field(offset, offset + width, parser))
        offset += width
    return layout


def _read_metadata(lines: Sequence[str]) -> tuple[list[str], str]:
    """Extract column names (line 4) and the format specification."""
    hdr_line_nos = cfg.data_config.gdr_format.header_line_number
    if len(lines) < hdr_line_nos:
        msg = f"File has fewer than {hdr_line_nos} lines."
        raise ValueError(msg)

    header_line = lines[hdr_line_nos - 1]
    if not header_line.lstrip().startswith(cfg.data_config.gdr_format.comment_prefix):
        msg = f"Line {hdr_line_nos} is not a comment header: {header_line!r}"
        raise ValueError(msg)
    columns = header_line.lstrip()[len(cfg.data_config.gdr_format.comment_prefix) :].split()

    spec = cfg.data_config.gdr_format.default_format
    for line in lines[:hdr_line_nos]:
        fmt_re = cfg.data_config.gdr_format.format_line_regex
        match = re.compile(fmt_re, re.IGNORECASE).search(line)
        if match is not None:
            spec = match["spec"].strip()
            break
    return columns, spec


def _iter_records(
    lines: Sequence[str], layout: Sequence[Field], first_line_number: int
) -> Iterator[list[str]]:
    """Yield validated rows of stripped field strings ('' denotes a missing value)."""
    record_width = layout[-1].stop
    for line_number, line in enumerate(lines, start=first_line_number):
        if not line.strip() or line.lstrip().startswith(cfg.data_config.gdr_format.comment_prefix):
            continue
        if len(line) > record_width and line[record_width:].strip():
            msg = f"Line {line_number}: content beyond declared record width {record_width}."
            raise ValueError(msg)
        padded = line.ljust(record_width)  # tolerate stripped trailing blanks
        row: list[str] = []
        for field in layout:
            token = padded[field.start : field.stop].strip()
            if token:
                try:
                    field.parser(token)  # validation only; original text is preserved
                except ValueError as exc:
                    msg = (
                        f"Line {line_number}, columns {field.start + 1}-{field.stop}: "
                        f"cannot parse {token!r}."
                    )
                    raise ValueError(msg) from exc
            row.append(token)
        yield row


def fortran_dat_to_csv(dat_path: Path, csv_path: Path, *, encoding: str = "utf-8") -> int:
    """Convert a fixed-width GDR ``.dat`` file to CSV.

    Args:
        dat_path: Path to the input ``.dat`` file.
        csv_path: Destination path for the CSV output (parent dirs are created).
        encoding: Text encoding of the input file.

    Returns:
        The number of data rows written.

    Raises:
        FileNotFoundError: If ``dat_path`` does not exist.
        ValueError: If the header, format, or any record is malformed.

    """
    with dat_path.open(encoding=encoding) as fh:
        lines = fh.read().splitlines()

    columns, spec = _read_metadata(lines)
    layout = _build_layout(spec)
    if len(columns) != len(layout):
        msg = (
            f"Header declares {len(columns)} columns but format {spec!r} "
            f"defines {len(layout)} fields."
        )
        raise ValueError(msg)

    csv_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = csv_path.with_suffix(csv_path.suffix + ".tmp")
    n_rows = 0
    try:
        with tmp_path.open("w", newline="", encoding="utf-8") as out:
            writer = csv.writer(out)
            writer.writerow(columns)
            body = lines[cfg.data_config.gdr_format.header_line_number :]
            for row in _iter_records(
                body, layout, cfg.data_config.gdr_format.header_line_number + 1
            ):
                writer.writerow(row)
                n_rows += 1
        tmp_path.replace(csv_path)  # atomic on POSIX/Windows for same filesystem
    except BaseException:
        tmp_path.unlink(missing_ok=True)
        raise
    return n_rows
